'use strict';
// The only local JS dependency is core.js. Inline it: Obsidian evaluates main.js
// with its own require(), which does not resolve sibling plugin modules.
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'../plugins/leetany');
const source=fs.readFileSync(path.join(root,'main.src.js'),'utf8');
const core=fs.readFileSync(path.join(root,'core.js'),'utf8');
const marker="require('./core')";
if(!source.includes(marker))throw new Error('Missing core import');
const bundle=source.replace(marker,`(()=>{ const module={exports:{}};\n${core}\nreturn module.exports; })()`);
fs.writeFileSync(path.join(root,'main.js'),'// Generated by scripts/build_leetany.cjs; edit main.src.js and core.js.\n'+bundle);
