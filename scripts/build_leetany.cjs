'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {buildSync} = require('esbuild');

const root = path.resolve(__dirname, '..');
// Use the editor packages provided by Obsidian and ship the Python grammar locally.
const licenses = ['@codemirror/lang-python', '@lezer/python'].map(pkg =>
  pkg + '\n' + fs.readFileSync(path.join(root, 'node_modules', pkg, 'LICENSE'), 'utf8'));
buildSync({
  absWorkingDir: root,
  entryPoints: ['plugins/leetany/main.src.js'],
  outfile: 'plugins/leetany/main.js',
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'es2021',
  external: ['obsidian', '@codemirror/view', '@codemirror/state', '@codemirror/language',
    '@codemirror/commands', '@codemirror/autocomplete', '@lezer/common', '@lezer/highlight', '@lezer/lr'],
  banner: {js: '/* Generated by npm run build.\n' + licenses.join('\n') + '*/'}
});
